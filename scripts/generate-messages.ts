#!/usr/bin/env node
// Generates the message catalog from the vendored upstream message bundles and default severities.
// Usage: node scripts/generate-messages.ts
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import * as Console from "effect/Console";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";

import { UpstreamManifestJson } from "./lib/upstream.ts";

class CatalogSourceError extends Schema.TaggedError<CatalogSourceError>()("CatalogSourceError", {
  source: Schema.String,
  reason: Schema.String,
}) {
  override get message(): string {
    return `Cannot generate the message catalog from ${this.source}: ${this.reason}.`;
  }
}

// Java .properties subset used by the EPUBCheck bundles: `key=value` lines, `#` comments, UTF-8.
const parseProperties = (text: string) => {
  const entries: Array<readonly [string, string]> = [];
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trimStart();
    if (line === "" || line.startsWith("#") || line.startsWith("!")) continue;
    const separator = line.search(/[=:]/);
    if (separator < 0) continue;
    const key = line.slice(0, separator).trim();
    const value = line
      .slice(separator + 1)
      .trimStart()
      .replace(/\\u([0-9a-fA-F]{4})/g, (_, hex: string) =>
        String.fromCharCode(Number.parseInt(hex, 16)),
      )
      .replace(/\\(.)/g, (_, char: string) => (char === "n" ? "\n" : char === "t" ? "\t" : char));
    entries.push([key, value]);
  }
  return entries;
};

const toMessageId = (javaName: string) => javaName.replace(/_/g, "-");

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const root = path.resolve(import.meta.dirname, "..");
  const vendor = path.join(root, "vendor", "epubcheck");
  const severitiesSource = path.join(
    vendor,
    "src/main/java/com/adobe/epubcheck/messages/DefaultSeverities.java",
  );
  const bundlesDir = path.join(vendor, "src/main/resources/com/adobe/epubcheck/messages");
  const upstream = yield* Schema.decodeEffect(UpstreamManifestJson)(
    yield* fs.readFileString(path.join(vendor, "UPSTREAM.json")),
  );

  const severities = [
    ...(yield* fs.readFileString(severitiesSource)).matchAll(
      /severities\.put\(MessageId\.([A-Z]{3}_\d{3}[a-z]?), Severity\.([A-Z]+)\);/g,
    ),
  ].map((match) => [toMessageId(match[1] ?? ""), match[2] ?? ""] as const);
  if (severities.length === 0) {
    return yield* new CatalogSourceError({
      source: severitiesSource,
      reason: "no severities found",
    });
  }

  const bundleFiles = (yield* fs.readDirectory(bundlesDir))
    .filter((name) => /^MessageBundle(_[A-Za-z_]+)?\.properties$/.test(name))
    .sort();
  const bundles: Array<readonly [string, ReadonlyArray<readonly [string, string]>]> = [];
  for (const file of bundleFiles) {
    const locale = file.replace(/^MessageBundle_?/, "").replace(/\.properties$/, "");
    const text = yield* fs.readFileString(path.join(bundlesDir, file));
    bundles.push([locale === "" ? "default" : locale.replace("_", "-"), parseProperties(text)]);
  }

  const lines = [
    `// Generated by scripts/generate-messages.ts from EPUBCheck ${upstream.tag} (vendor/epubcheck). Do not edit.`,
    "// Message text and severities: Copyright (c) the EPUBCheck contributors, BSD-3-Clause.",
    "",
    "export const defaultSeverities = {",
    ...severities.map(([id, severity]) => `  ${JSON.stringify(id)}: ${JSON.stringify(severity)},`),
    "} as const;",
    "",
    "export const bundles: Readonly<Record<string, Readonly<Record<string, string>>>> = {",
    ...bundles.flatMap(([locale, entries]) => [
      `  ${JSON.stringify(locale)}: {`,
      ...entries.map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`),
      "  },",
    ]),
    "};",
    "",
  ];
  const target = path.join(root, "packages/epubcheck/src/messages/catalog.generated.ts");
  yield* fs.makeDirectory(path.dirname(target), { recursive: true });
  yield* fs.writeFileString(target, lines.join("\n"));
  yield* Console.log(
    `Wrote ${severities.length} message IDs and ${bundles.length} bundles to ${path.relative(root, target)}`,
  );
});

program.pipe(Effect.provide(NodeServices.layer), NodeRuntime.runMain);
