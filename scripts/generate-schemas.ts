#!/usr/bin/env node
// Embeds the vendored upstream schemas (RELAX NG, Schematron, NVDL) into a generated module.
// Usage: node scripts/generate-schemas.ts
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import * as Console from "effect/Console";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";

import { UpstreamManifestJson } from "./lib/upstream.ts";

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const root = path.resolve(import.meta.dirname, "..");
  const vendor = path.join(root, "vendor", "epubcheck");
  const schemaDir = path.join(vendor, "src/main/resources/com/adobe/epubcheck/schema");
  const upstream = yield* Schema.decodeEffect(UpstreamManifestJson)(
    yield* fs.readFileString(path.join(vendor, "UPSTREAM.json")),
  );
  const files = (yield* fs.readDirectory(schemaDir, { recursive: true }))
    .map((file) => file.split(path.sep).join("/"))
    .filter((file) => /\.(rnc|rng|sch|nvdl|dtd|ent|mod)$/.test(file))
    .sort();
  const lines = [
    `// Generated by scripts/generate-schemas.ts from EPUBCheck ${upstream.tag} (vendor/epubcheck). Do not edit.`,
    "// Each schema keeps its own license; see THIRD_PARTY_NOTICES.md.",
    "",
    "export const sources: Readonly<Record<string, string>> = {",
  ];
  for (const file of files) {
    const text = yield* fs.readFileString(path.join(schemaDir, file));
    lines.push(`  ${JSON.stringify(file)}: ${JSON.stringify(text)},`);
  }
  lines.push("};", "");
  const target = path.join(root, "packages/epubcheck/src/schema/sources.generated.ts");
  yield* fs.writeFileString(target, lines.join("\n"));
  yield* Console.log(`Embedded ${files.length} schema files in ${path.relative(root, target)}`);
});

program.pipe(Effect.provide(NodeServices.layer), NodeRuntime.runMain);
